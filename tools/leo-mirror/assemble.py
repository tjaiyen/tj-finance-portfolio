def require(cond, msg):
    """Every guard below is load-bearing: it is how a changed reference bundle
    becomes a loud build failure instead of a page that quietly lost a link.
    `assert` cannot do that job -- python3 -O (or PYTHONOPTIMIZE=1 in a CI image)
    strips assertions, and this script then exits 0 having silently skipped the
    deviation. Proven: with -O and a one-character change to the Glossary
    button's style, the build "succeeded" with both companion-page links gone."""
    if not cond:
        raise SystemExit('assemble.py: ' + msg)

