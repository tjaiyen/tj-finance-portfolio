_VOID = {'br', 'hr', 'img', 'input', 'meta', 'link', 'source', 'use', 'stop', 'col'}
_TAG = re.compile(r'<(/?)([\w-]+)((?:"[^"]*"|[^>"])*?)(/?)>', re.S)


class _El(object):
    __slots__ = ('tag', 'attrs', 'start', 'parent', 'kids')

    def __init__(self, tag, attrs, start, parent):
        self.tag, self.attrs, self.start, self.parent, self.kids = tag, attrs, start, parent, []

    @property
    def style(self):
        m = re.search(r'\bstyle="([^"]*)"', self.attrs)
        return m.group(1) if m else ''


def _parse(src):
    """Tag tree. sc-for / sc-if are kept as nodes; they vanish at compile time,
    so the walkers below step over them to get the element that will really be
    the parent in the rendered DOM."""
    root = _El('#root', '', 0, None)
    stack = [root]
    for m in _TAG.finditer(src):
        closing, tag, attrs, selfclose = m.groups()
        if closing:
            for i in range(len(stack) - 1, 0, -1):
                if stack[i].tag == tag:
                    del stack[i:]
                    break
            continue
        el = _El(tag, attrs, m.start(), stack[-1])
        stack[-1].kids.append(el)
        if not selfclose and tag not in _VOID:
            stack.append(el)
    return root


def _every(el, out):
    out.append(el)
    for k in el.kids:
        _every(k, out)
    return out


def _eff_kids(el):
    out = []
    for k in el.kids:
        out.extend(_eff_kids(k) if k.tag in ('sc-for', 'sc-if') else [k])
    return out


def _eff_parent(el):
    p = el.parent
    while p is not None and p.tag in ('sc-for', 'sc-if'):
        p = p.parent
    return p


def _cols(spec):
    """Column count of a grid-template-columns value (repeat() expanded)."""
    parts, depth, buf = [], 0, ''
    for ch in spec:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ' ' and depth == 0:
            if buf:
                parts.append(buf)
            buf = ''
        else:
            buf += ch
    if buf:
        parts.append(buf)
    n = 0
    for p in parts:
        m = re.match(r'repeat\((\d+),', p)
        n += int(m.group(1)) if m else 1
    return n


def _table_roles(src):
    allel = _every(_parse(src), [])
    ins = {}                       # element start offset -> role
    def put(el, role):
        pos = el.start + 1 + len(el.tag)
        require(ins.get(pos, role) == role, 'conflicting role at %d' % pos)
        ins[pos] = role

    for spec in TABLE_GRIDS:
        needle = 'grid-template-columns:%s;' % spec
        rows = [e for e in allel if 'display:grid' in e.style and needle in e.style]
        # one header row plus one row template per table; a change to the
        # reference that breaks this should fail loudly, not silently skip
        require(len(rows) == 2, '%r: %d row nodes, expected 2' % (spec[:40], len(rows)))
        container = min((_eff_parent(r) for r in rows), key=lambda p: p.start)
        ncols = _cols(spec)
        headers = 0
        for r in rows:
            # anything between the container and the row is a scroll wrapper or
            # similar; it has to be a rowgroup or it breaks the owned structure
            node, in_loop = r.parent, False
            while node is not container:
                require(node is not None, '%r: container is not an ancestor' % spec[:40])
                if node.tag == 'sc-for':
                    in_loop = True
                elif node.tag != 'sc-if':
                    put(node, 'rowgroup')
                node = node.parent
            cells = _eff_kids(r)
            require(len(cells) == ncols, '%r: %d cells, %d columns' % (spec[:40], len(cells), ncols))
            for c in cells:
                put(c, 'cell' if in_loop else 'columnheader')
            put(r, 'row')
            headers += 0 if in_loop else 1
        require(headers == 1, '%r: %d header rows' % (spec[:40], headers))
        put(container, 'table')

    for pos in sorted(ins, reverse=True):
        src = src[:pos] + ' role="%s"' % ins[pos] + src[pos:]
    return src, ins


